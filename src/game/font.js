// Мініатюрний бітмап-шрифт 3×5 для чисел усередині canvas («+1», «+5»).
const GLYPHS = {
  0: ['111', '101', '101', '101', '111'],
  1: ['010', '110', '010', '010', '111'],
  2: ['111', '001', '111', '100', '111'],
  3: ['111', '001', '011', '001', '111'],
  4: ['101', '101', '111', '001', '001'],
  5: ['111', '100', '111', '001', '111'],
  6: ['111', '100', '111', '101', '111'],
  7: ['111', '001', '010', '010', '010'],
  8: ['111', '101', '111', '101', '111'],
  9: ['111', '101', '111', '001', '111'],
  '+': ['000', '010', '111', '010', '000'],
  '-': ['000', '000', '111', '000', '000'],
};

export function textWidth(text) {
  return text.length * 4 - 1;
}

// Малює текст із центром у точці x. Тінь знизу-справа для читабельності на будь-якому фоні.
export function drawPixelText(ctx, text, x, y, color, shadow = '#1d1b26') {
  let cx = Math.round(x - textWidth(text) / 2);
  const cy = Math.round(y);
  for (const ch of text) {
    const g = GLYPHS[ch];
    if (g) {
      for (let r = 0; r < 5; r++) {
        for (let c = 0; c < 3; c++) {
          if (g[r][c] !== '1') continue;
          ctx.fillStyle = shadow;
          ctx.fillRect(cx + c + 1, cy + r + 1, 1, 1);
          ctx.fillStyle = color;
          ctx.fillRect(cx + c, cy + r, 1, 1);
        }
      }
    }
    cx += 4;
  }
}
